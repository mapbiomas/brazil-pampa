// Função para equilibrar amostras e transformar em binário (afloramento = 1, resto = 0)
function balanceAndBinarize(samples, classe_afloramento) {
  var afloramento = samples.filter(ee.Filter.eq('reference', classe_afloramento));
  var nao_afloramento = samples.filter(ee.Filter.neq('reference', classe_afloramento));
  
  print("Total de Amostras Aroc disponíveis na áreas de ARoc:", afloramento.size())
  var n_afloramento = n_amostras*propAroc;
  var n_nao_afloramento = n_amostras; 
  
  // Sorteia n_amostras de não afloramento
  var afloramento_sampled = afloramento.randomColumn('random').sort('random').limit(n_afloramento);
  var nao_afloramento_sampled = nao_afloramento.randomColumn('random').sort('random').limit(n_nao_afloramento);
  
  // Junta afloramento + não afloramento balanceados
  var balanced = afloramento_sampled.merge(nao_afloramento_sampled);
  
  // Transforma a propriedade 'reference' em binária: 1 para afloramento, 0 para o resto
  balanced = balanced.map(function (f) {
    var isAfloramento = ee.Number(f.get('reference')).eq(classe_afloramento);
    return f.set('reference', isAfloramento);
  });
  
  return balanced;
}
